/// The dedicated home for the brainpoolP384r1 domain parameters.
///
/// RFC 5639 section 3.6 publishes these as big-endian hex strings. They are
/// transcribed here exactly once, as little-endian 64-bit limb literals in
/// the layout `U384` stores, so no hex parser exists at runtime and nothing
/// in the curve code has a parse result to force-unwrap. Each limb is a named
/// binding, in order from least to most significant.
///
/// The transcription is checked mechanically by `BrainpoolP384r1Tests`: the
/// generator's SEC1 encoding is compared against the RFC's big-endian hex,
/// the generator satisfies the curve equation, and `n * G` is the point at
/// infinity. No wrong limb survives all three.
///
/// Provenance: lifted from the RefineID iOS browser donor
/// `Sources/RefineIDBrowserKit/Crypto/BrainpoolP384.swift` and
/// `Sources/RefineIDBrowserKit/Crypto/FieldP384.swift`, whose big-endian hex
/// constants these limbs encode.
