  }()

  /// The `y` coordinate of the base point `G`.
  internal static let generatorY: U384 = {
    let limb0: UInt64 = 0xCBB6_4068_37BF_51F5
    let limb1: UInt64 = 0x2BCE_3357_6B31_5ECE
