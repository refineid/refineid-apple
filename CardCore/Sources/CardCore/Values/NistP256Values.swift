/// The dedicated home for the NIST P-256 (`secp256r1`) domain parameters.
///
/// FIPS 186-4 appendix D.1.2.3 and SEC 2 v2 section 2.4.2 publish these
/// as big-endian hex. They are transcribed here exactly once, as
/// little-endian 64-bit limb literals in the layout `U384` stores, so no
/// hex parser exists at runtime. Each limb is a named binding, in order
/// from least to most significant; a 256-bit value leaves the limbs above
/// it zero.
///
/// The transcription is checked mechanically by `NistCurveTests`: the
/// generator equals the public key CryptoKit derives from the scalar one,
/// arbitrary scalar multiples equal CryptoKit's public keys for the same
/// scalars, and `n * G` is the point at infinity. No wrong limb survives
/// all three.
internal enum NistP256Values {
  /// The field prime `p`.
  internal static let prime: U384 = {
    let limb0: UInt64 = 0xFFFF_FFFF_FFFF_FFFF
    let limb1: UInt64 = 0x0000_0000_FFFF_FFFF
    let limb2: UInt64 = 0x0000_0000_0000_0000
    let limb3: UInt64 = 0xFFFF_FFFF_0000_0001
    let limb4: UInt64 = 0x0000_0000_0000_0000
    let limb5: UInt64 = 0x0000_0000_0000_0000
    return U384(
      limb0: limb0,
      limb1: limb1,
      limb2: limb2,
      limb3: limb3,
      limb4: limb4,
      limb5: limb5
    )
  }()

  /// The curve equation coefficient `A = p - 3` in `y^2 = x^3 + A*x + B`.
  internal static let coefficientA: U384 = {
    let limb0: UInt64 = 0xFFFF_FFFF_FFFF_FFFC
    let limb1: UInt64 = 0x0000_0000_FFFF_FFFF
    let limb2: UInt64 = 0x0000_0000_0000_0000
    let limb3: UInt64 = 0xFFFF_FFFF_0000_0001
    let limb4: UInt64 = 0x0000_0000_0000_0000
    let limb5: UInt64 = 0x0000_0000_0000_0000
    return U384(
      limb0: limb0,
      limb1: limb1,
      limb2: limb2,
      limb3: limb3,
      limb4: limb4,
      limb5: limb5
    )
  }()

  /// The curve equation coefficient `B` in `y^2 = x^3 + A*x + B`.
  internal static let coefficientB: U384 = {
    let limb0: UInt64 = 0x3BCE_3C3E_27D2_604B
    let limb1: UInt64 = 0x651D_06B0_CC53_B0F6
    let limb2: UInt64 = 0xB3EB_BD55_7698_86BC
    let limb3: UInt64 = 0x5AC6_35D8_AA3A_93E7
    let limb4: UInt64 = 0x0000_0000_0000_0000
    let limb5: UInt64 = 0x0000_0000_0000_0000
    return U384(
      limb0: limb0,
      limb1: limb1,
      limb2: limb2,
      limb3: limb3,
      limb4: limb4,
      limb5: limb5
    )
  }()

  /// The `x` coordinate of the base point `G`.
  internal static let generatorX: U384 = {
    let limb0: UInt64 = 0xF4A1_3945_D898_C296
    let limb1: UInt64 = 0x7703_7D81_2DEB_33A0
    let limb2: UInt64 = 0xF8BC_E6E5_63A4_40F2
    let limb3: UInt64 = 0x6B17_D1F2_E12C_4247
    let limb4: UInt64 = 0x0000_0000_0000_0000
    let limb5: UInt64 = 0x0000_0000_0000_0000
    return U384(
      limb0: limb0,
      limb1: limb1,
      limb2: limb2,
      limb3: limb3,
      limb4: limb4,
      limb5: limb5
