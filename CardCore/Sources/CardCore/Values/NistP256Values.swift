  }()

  /// The order `n` of the subgroup generated by `G`; the cofactor is 1.
  internal static let order: U384 = {
    let limb0: UInt64 = 0xF3B9_CAC2_FC63_2551
    let limb1: UInt64 = 0xBCE6_FAAD_A717_9E84
    let limb2: UInt64 = 0xFFFF_FFFF_FFFF_FFFF
    let limb3: UInt64 = 0xFFFF_FFFF_0000_0000
    let limb4: UInt64 = 0x0000_0000_0000_0000
    let limb5: UInt64 = 0x0000_0000_0000_0000
