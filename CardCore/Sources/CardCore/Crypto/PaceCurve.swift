/// A curve PACE runs over: one of the standardized domain parameters the
/// FINEID cards publish in EF.CardAccess (BSI TR-03110-3 table 4).
///
/// Each conforming type carries its transcribed parameters; the group
/// arithmetic below is shared. CryptoKit offers NIST P-256 and P-384 only
/// as key agreement, which hands out the x-coordinate of a shared point and
/// never a point itself, and offers no Brainpool curve at all; the generic
/// mapping needs full point addition and scalar multiplication, so the
/// arithmetic is ours.
///
/// Scalar multiplication is double-and-add and is not constant-time. The
/// scalars it consumes are the ephemeral, single-use PACE keys, matching the
/// stated posture of the Rust reference implementation; it must not be given
/// a long-lived private key.
public protocol PaceCurve: Sendable {
  /// The curve's domain parameters.
  static var parameters: CurveDomainParameters { get }
}

extension PaceCurve {
  /// `A` as a field element.
  internal static var coefficientA: CurveFieldElement<Self> {
    CurveFieldElement(montgomery: parameters.montgomeryA)
  }

  /// `B` as a field element.
  internal static var coefficientB: CurveFieldElement<Self> {
    CurveFieldElement(montgomery: parameters.montgomeryB)
  }

  /// The base point `G`.
  public static var generator: CurvePoint<Self> {
    CurvePoint(onCurveX: parameters.generatorX, onCurveY: parameters.generatorY)
  }

  /// The order `n` of the subgroup generated by `G`.
  public static var order: U384 {
    parameters.order
  }

  /// The width of one coordinate and of one scalar, in bytes.
  public static var coordinateByteCount: Int {
    parameters.coordinateByteCount
  }

  /// `scalar * point`, by double-and-add from the scalar's highest set bit.
  ///
  /// Intermediate points use Jacobian coordinates. Affine addition and
  /// doubling each need a field inversion; keeping `Z` avoids hundreds of
  /// those inversions and pays for exactly one when the final point is
  /// converted back to the public affine representation.
  ///
  /// A zero scalar gives the point at infinity.
  public static func multiply(_ point: CurvePoint<Self>, by scalar: U384) -> CurvePoint<Self> {
    guard let highestBit = scalar.highestSetBitIndex, !point.isInfinity else {
      return .infinity
    }
    var result = JacobianPoint<Self>.infinity
    for index in stride(from: highestBit, through: 0, by: -1) {
      result = result.doubled()
      if scalar.bit(at: index) {
        result = result.adding(point)
      }
    }
    return result.affinePoint()
  }

  /// `scalar * G`, the public point of a private scalar.
  public static func multiplyGenerator(by scalar: U384) -> CurvePoint<Self> {
    multiply(Self.generator, by: scalar)
  }
}
