# Writes Sources/App/DeviceModels.swift from the device database Xcode
# ships with the iOS platform: every iPhone and iPad machine identifier
# with the name on its box. Run it after an Xcode update and commit the
# result; the application maps the identifier uname reports through it.
set -eu
cd "$(dirname "$0")/.."
platform="$(xcode-select -p)/Platforms/iPhoneOS.platform/usr/standalone/device_traits.db"
out=Sources/App/DeviceModels.swift
xcode="$(xcodebuild -version | head -1)"
{
  echo "// Copyright 2026 Petri Koistinen. Licensed under the Apache License, Version 2.0."
  echo "//"
  echo "// Generated by Scripts/generate-device-models.sh from the device database"
  echo "// of $xcode. Do not edit; run the script after an Xcode update."
  echo ""
  echo "/// Apple machine identifiers and the names on the box, as Xcode knows them."
  echo "internal enum DeviceModels {"
  echo "  internal static let names: [String: String] = ["
  sqlite3 -separator '|' "$platform" \
    "select ProductType, ProductDescription from Devices
     where ProductDescription is not null and (ProductType like 'iPhone%' or ProductType like 'iPad%')
     group by ProductType order by ProductType" \
    | awk -F'|' '{ printf "    \"%s\": \"%s\",\n", $1, $2 }'
  echo "  ]"
  echo "}"
} > "$out"
echo "wrote $out ($(grep -c '": "' "$out") devices)"
