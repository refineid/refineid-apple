# Writes CardCore/Sources/CardCore/DeviceModels.swift from the device database Xcode
# ships with the iOS platform: every iPhone and iPad machine identifier
# with the name on its box. Run it after an Xcode update and commit the
# result; the application maps the identifier uname reports through it.

from __future__ import annotations

import os
from pathlib import Path
import sqlite3
import subprocess
import sys


def main() -> None:
    repo_root = Path(__file__).resolve().parent.parent
    os.chdir(repo_root)

    xcode_developer = subprocess.run(
        ["xcode-select", "-p"],
        capture_output=True,
        text=True,
        check=True,
    ).stdout.strip()

    db_path = Path(xcode_developer) / "Platforms/iPhoneOS.platform/usr/standalone/device_traits.db"
    if not db_path.is_file():
        print(f"Error: device traits database not found at {db_path}", file=sys.stderr)
        sys.exit(1)

    out_file = repo_root / "CardCore/Sources/CardCore/DeviceModels.swift"

    xcode_version_out = subprocess.run(
        ["xcodebuild", "-version"],
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    xcode_version = xcode_version_out.splitlines()[0] if xcode_version_out else "Xcode"

    conn = sqlite3.connect(db_path)
    cursor = conn.cursor()
    query = """
    select case when instr(ProductType, '-') > 0 then substr(ProductType, 1, instr(ProductType, '-') - 1) else ProductType end as Identifier, ProductDescription
    from Devices
    where ProductDescription is not null and (ProductType like 'iPhone%' or ProductType like 'iPad%')
    group by Identifier order by Identifier
    """
    rows = cursor.execute(query).fetchall()
    conn.close()

    lines: list[str] = [
        "// Copyright 2026 Petri Koistinen. Licensed under the Apache License, Version 2.0.",
        "//",
        f"// Generated by Scripts/generate-device-models.py from the device database",
        f"// of {xcode_version}. Do not edit; run the script after an Xcode update.",
        "",
        "/// Apple machine identifiers and the names on the box, as Xcode knows them.",
        "internal enum DeviceModels {",
        "  internal static let names: [String: String] = [",
    ]

    for ident, desc in rows:
        lines.append(f'    "{ident}": "{desc}",')

    lines.append("  ]")
    lines.append("}")

    out_file.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out_file.relative_to(repo_root)} ({len(rows)} devices)")


if __name__ == "__main__":
    main()
